def _validate_user_id(user_id: int) -> int:
    """Validate and normalize the authenticated user ID."""

    try:
        user_id = int(user_id)
    except (TypeError, ValueError) as error:
        raise ValueError(
            "user_id must be a valid integer."
        ) from error

    if user_id <= 0:
        raise ValueError(
            "user_id must be greater than 0."
        )

    return user_id


def _clean_filename(filename: str) -> str:
    """Validate a PDF filename."""

    if filename is None:
        raise ValueError(
            "filename cannot be empty."
        )

    filename = str(filename).strip()

    if not filename:
        raise ValueError(
            "filename cannot be empty."
        )

    return filename


def _get_collection_name(user_id: int) -> str:
    """Return the isolated ChromaDB collection name for a user."""

    user_id = _validate_user_id(user_id)

    return (
        f"{COLLECTION_PREFIX}"
        f"{user_id}"
        f"_documents"
    )


def _safe_int(
    value: Any,
    default: int = 0,
) -> int:
    """Safely convert a value to integer."""

    try:
        return int(value)
    except (TypeError, ValueError):
        return default


def _safe_float(
    value: Any,
    default: float = 0.0,
) -> float:
    """Safely convert a value to float."""

    try:
        return float(value)
    except (TypeError, ValueError):
        return default


# ============================================================
# TEXT / TOKEN HELPERS
# ============================================================

def _normalize_text(text: Any) -> str:
    """
    Normalize whitespace without destroying page markers or
    meaningful document content.
    """

    if text is None:
        return ""

    text = str(text)

    # Normalize Windows and old-Mac line endings.
    text = text.replace("\r\n", "\n")
    text = text.replace("\r", "\n")

    # Normalize tabs.
    text = text.replace("\t", " ")

    # Keep newlines but collapse excessive spaces.
    text = re.sub(
        r"[ ]{2,}",
        " ",
        text,
    )

    # Collapse excessive blank lines.
    text = re.sub(
        r"\n{3,}",
        "\n\n",
        text,
    )

    return text.strip()


def _tokenize(text: str) -> Set[str]:
    """
    Tokenize text for lightweight lexical relevance scoring.

    This does NOT replace semantic embeddings.
    It only helps OCR-heavy queries where exact terminology
    can be important.
    """

    if not text:
        return set()

    tokens = {
        token.lower()
        for token in TOKEN_PATTERN.findall(
            str(text)
        )
    }

    return {
        token
        for token in tokens
        if len(token) >= 2
        and token not in STOP_WORDS
    }


def _calculate_lexical_overlap(
    query_tokens: Set[str],
    document: str,
) -> float:
    """
    Calculate query-token coverage inside a document.

    Example:
        Query: "multilevel inheritance"
        Document contains both terms
        -> high score
    """

    if not query_tokens:
        return 0.0

    document_tokens = _tokenize(document)

    if not document_tokens:
        return 0.0

    matched = query_tokens.intersection(
        document_tokens
    )

    return (
        len(matched)
        / max(len(query_tokens), 1)
    )


def _calculate_token_frequency_score(
    query_tokens: Set[str],
    document: str,
) -> float:
    """
    Small supporting lexical score based on repeated
    query terminology.

    This is intentionally capped so repeated OCR text cannot
    overpower semantic similarity.
    """

    if not query_tokens or not document:
        return 0.0

    document_tokens = [
        token.lower()
        for token in TOKEN_PATTERN.findall(
            str(document)
        )
    ]

    if not document_tokens:
        return 0.0

    document_token_set = set(document_tokens)

    matched_tokens = query_tokens.intersection(
        document_token_set
    )

    if not matched_tokens:
        return 0.0

    frequency_total = 0

    for token in matched_tokens:
        frequency_total += document_tokens.count(
            token
        )

    # Small bounded score.
    return min(
        frequency_total / max(len(document_tokens), 1),
        0.25,
    )


# ============================================================
# PAGE METADATA HELPERS
# ============================================================

def _extract_page_numbers(
    chunk: str,
) -> List[int]:
    """
    Extract every [Page N] marker from a chunk.
    """

    if not chunk:
        return []

    page_numbers: List[int] = []

    for value in PAGE_MARKER_PATTERN.findall(
        str(chunk)
    ):
        page = _safe_int(
            value,
            0,
        )

        if (
            page > 0
            and page not in page_numbers
        ):
            page_numbers.append(page)

    return page_numbers


def _build_page_metadata(
    chunk: str,
) -> Dict[str, Any]:
    """
    Build normalized page metadata for a chunk.
    """

    page_numbers = _extract_page_numbers(
        chunk
    )

    if not page_numbers:
        return {
            "page_number": 0,
            "page_numbers": "",
        }

    return {
        "page_number": page_numbers[0],
        "page_numbers": ",".join(
            str(page)
            for page in page_numbers
        ),
    }


# ============================================================
# EMBEDDING VALIDATION
# ============================================================

def _embedding_to_list(
    embedding: Sequence[float],
    index: int,
) -> List[float]:
    """
    Convert an embedding to a validated float list.
    """

    if embedding is None:
        raise ValueError(
            f"Embedding {index} cannot be None."
        )

    try:
        values = [
            float(value)
            for value in embedding
        ]
    except (TypeError, ValueError) as error:
        raise ValueError(
            f"Embedding {index} contains invalid values."
        ) from error

    if not values:
        raise ValueError(
            f"Embedding {index} cannot be empty."
        )

    for value in values:
        if not math.isfinite(value):
            raise ValueError(
                f"Embedding {index} contains "
                "NaN or infinite values."
            )

    return values


def _validate_embedding_dimensions(
    embeddings: Sequence[
        Sequence[float]
    ],
) -> int:
    """
    Ensure every embedding has the same dimension.
    """

    if not embeddings:
        raise ValueError(
            "Embeddings cannot be empty."
        )

    dimension = len(
        embeddings[0]
    )

    if dimension == 0:
        raise ValueError(
            "Embedding dimension cannot be zero."
        )

    for index, embedding in enumerate(
        embeddings
    ):
        if len(embedding) != dimension:
            raise ValueError(
                "Embedding dimension mismatch at "
                f"index {index}. "
                f"Expected {dimension}, "
                f"received {len(embedding)}."
            )

    return dimension


# ============================================================
# DETERMINISTIC CHUNK ID
# ============================================================

def _create_chunk_id(
    user_id: int,
    filename: str,
    chunk_index: int,
    chunk: str,
) -> str:
    """
    Create a deterministic and collision-resistant Chroma ID.

    The chunk index is included so two identical chunks appearing
    at different positions remain separate vectors.
    """

    raw_id = (
        f"{user_id}::"
        f"{filename}::"
        f"{chunk_index}::"
        f"{chunk}"
    )

    digest = hashlib.sha256(
        raw_id.encode("utf-8")
    ).hexdigest()

    return (
        f"{COLLECTION_PREFIX}"
        f"{user_id}_"
        f"{digest}"
    )



# GET DOCUMENT STATISTICS
# ============================================================

def get_document_stats(
    user_id: int,
    filename: str,
) -> Dict[str, Any]:
    """
    Return indexed chunk, character and page statistics.
    """

    user_id = _validate_user_id(
        user_id
    )

    filename = _clean_filename(
        filename
    )

    collection = get_collection(
        user_id
    )

    try:
        result = collection.get(
            where={
                "filename": filename
            },
            include=[
                "metadatas",
                "documents",
            ],
        )

    except Exception as error:
        print(
            "[VectorStore] Failed to retrieve "
            "document stats:",
            repr(error),
        )

        raise RuntimeError(
            "Unable to retrieve document statistics."
        ) from error

    documents = (
        result.get(
            "documents",
            [],
        )
        if result
        else []
    )

    metadatas = (
        result.get(
            "metadatas",
            [],
        )
        if result
        else []
    )

    pages: List[int] = []

    characters = sum(
        len(
            str(
                document
                or ""
            )
        )
        for document in documents
    )

    for metadata in metadatas:
        if not metadata:
            continue

        page_values = str(
            metadata.get(
                "page_numbers",
                "",
            )
            or ""
        ).split(",")

        for value in page_values:
            page = _safe_int(
                value.strip(),
                0,
            )

            if (
                page > 0
                and page not in pages
            ):
                pages.append(page)

    pages.sort()

    return {
        "user_id": user_id,
        "filename": filename,
        "chunks": len(
            documents
        ),
        "characters": characters,
        "pages": pages,
        "page_count": len(
            pages
        ),
    }



# GET DOCUMENT SOURCE PAGES
# ============================================================

def get_document_source_pages(
    user_id: int,
    filename: str,
) -> List[int]:
    """
    Return all unique source pages represented by indexed chunks.
    """

    user_id = _validate_user_id(
        user_id
    )

    filename = _clean_filename(
        filename
    )

    collection = get_collection(
        user_id
    )

    try:
        result = collection.get(
            where={
                "filename": filename
            },
            include=["metadatas"],
        )

    except Exception as error:
        print(
            "[VectorStore] Failed to retrieve "
            "document source pages:",
            repr(error),
        )

        raise RuntimeError(
            "Unable to retrieve document source pages."
        ) from error

    metadatas = (
        result.get(
            "metadatas",
            [],
        )
        if result
        else []
    )

    pages: List[int] = []

    for metadata in metadatas:
        if not metadata:
            continue

        page_numbers = str(
            metadata.get(
                "page_numbers",
                "",
            )
            or ""
        )

        for value in page_numbers.split(
            ","
        ):
            page = _safe_int(
                value.strip(),
                0,
            )

            if (
                page > 0
                and page not in pages
            ):
                pages.append(page)

    return sorted(
        pages
    )



# DOCUMENT INSPECTION
# ============================================================

def inspect_document(
    user_id: int,
    filename: str,
    max_chunks: int = 10,
) -> List[
    Dict[str, Any]
]:
    """
    Return a compact read-only inspection of indexed chunks.

    Useful while debugging OCR/chunking/RAG problems.
    """

    user_id = _validate_user_id(
        user_id
    )

    filename = _clean_filename(
        filename
    )

    try:
        max_chunks = max(
            1,
            int(
                max_chunks
            ),
        )
    except (
        TypeError,
        ValueError,
    ):
        max_chunks = 10

    collection = get_collection(
        user_id
    )

    try:
        result = collection.get(
            where={
                "filename": filename
            },
            include=[
                "documents",
                "metadatas",
            ],
        )

    except Exception as error:
        print(
            "[VectorStore] Failed to inspect document:",
            repr(error),
        )

        raise RuntimeError(
            "Unable to inspect document."
        ) from error

    documents = (
        result.get(
            "documents",
            [],
        )
        if result
        else []
    )

    metadatas = (
        result.get(
            "metadatas",
            [],
        )
        if result
        else []
    )

    # Chroma's get order is not guaranteed to be the original
    # insertion order. Sort chunks by their stored chunk index.
    rows_with_index: List[
        Tuple[int, Dict[str, Any]]
    ] = []

    for index, document in enumerate(
        documents
    ):
        metadata = (
            metadatas[index]
            if index < len(
                metadatas
            )
            else {}
        ) or {}

        chunk_index = _safe_int(
            metadata.get(
                "chunk_index",
                index,
            ),
            index,
        )

        rows_with_index.append(
            (
                chunk_index,
                {
                    "chunk_index": chunk_index,
                    "page_number": metadata.get(
                        "page_number",
                        0,
                    ),
                    "page_numbers": metadata.get(
                        "page_numbers",
                        "",
                    ),
                    "characters": len(
                        str(
                            document
                            or ""
                        )
                    ),
                    "preview": str(
                        document
                        or ""
                    )[:500],
                },
            )
        )

    rows_with_index.sort(
        key=lambda item: item[0]
    )

    return [
        row
        for _, row in rows_with_index[
            :max_chunks
        ]
    ]



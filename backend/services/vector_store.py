def get_collection(user_id: int):
    """
    Return the authenticated user's isolated ChromaDB collection.
    """

    collection_name = _get_collection_name(
        user_id
    )

    try:
        return chroma_client.get_or_create_collection(
            name=collection_name,
            metadata={
                "hnsw:space": "cosine",
                "user_id": str(user_id),
            },
        )

    except Exception as error:
        print(
            "[VectorStore] Unable to access collection:",
            repr(error),
        )

        raise RuntimeError(
            "Unable to access ChromaDB collection."
        ) from error


# ============================================================
# DELETE EXISTING DOCUMENT
# ============================================================

def _get_document_ids(
    collection,
    filename: str,
) -> List[str]:
    """
    Return all vector IDs belonging to one filename.
    """

    try:
        existing = collection.get(
            where={
                "filename": filename
            },
            include=["metadatas"],
        )

    except Exception as error:
        print(
            "[VectorStore] Failed to inspect "
            f"document '{filename}':",
            repr(error),
        )

        raise RuntimeError(
            "Unable to inspect existing document vectors."
        ) from error

    if not existing:
        return []

    return list(
        existing.get(
            "ids",
            [],
        ) or []
    )


def _delete_existing_document(
    collection,
    filename: str,
) -> int:
    """
    Delete all vectors for a filename.

    This makes re-uploading a PDF replace its old vectors
    rather than accumulating duplicates.
    """

    ids = _get_document_ids(
        collection,
        filename,
    )

    if not ids:
        return 0

    try:
        collection.delete(
            ids=ids
        )

        return len(ids)

    except Exception as error:
        print(
            "[VectorStore] Failed to remove "
            f"existing document '{filename}':",
            repr(error),
        )

        raise RuntimeError(
            "Unable to replace existing document vectors."
        ) from error


# ============================================================
# STORE CHUNKS
# ============================================================

def store_chunks(
    user_id: int,
    filename: str,
    chunks: Sequence[str],
    embeddings: Sequence[
        Sequence[float]
    ],
) -> int:
    """
    Replace all existing vectors for this filename and store
    the new chunk/embedding set.

    Public signature is intentionally preserved for main.py.
    """

    user_id = _validate_user_id(
        user_id
    )

    filename = _clean_filename(
        filename
    )

    if not chunks:
        raise ValueError(
            "chunks cannot be empty."
        )

    if not embeddings:
        raise ValueError(
            "embeddings cannot be empty."
        )

    if len(chunks) != len(
        embeddings
    ):
        raise ValueError(
            "Chunk count and embedding count "
            "must be identical."
        )

    # --------------------------------------------------------
    # Clean chunks
    # --------------------------------------------------------

    clean_chunks: List[str] = []

    for index, chunk in enumerate(
        chunks
    ):
        if chunk is None:
            raise ValueError(
                f"Chunk {index} cannot be None."
            )

        cleaned = _normalize_text(
            chunk
        )

        if not cleaned:
            raise ValueError(
                f"Chunk {index} cannot be empty."
            )

        clean_chunks.append(
            cleaned
        )

    # --------------------------------------------------------
    # Validate embeddings
    # --------------------------------------------------------

    clean_embeddings = [
        _embedding_to_list(
            embedding,
            index,
        )
        for index, embedding in enumerate(
            embeddings
        )
    ]

    embedding_dimension = (
        _validate_embedding_dimensions(
            clean_embeddings
        )
    )

    # --------------------------------------------------------
    # Logging
    # --------------------------------------------------------

    print()
    print(
        "[VectorStore] Preparing document:"
    )
    print(
        f"  User ID          : {user_id}"
    )
    print(
        f"  Filename         : {filename}"
    )
    print(
        f"  Chunks           : {len(clean_chunks)}"
    )
    print(
        f"  Embedding size   : "
        f"{embedding_dimension}"
    )

    collection = get_collection(
        user_id
    )

    # --------------------------------------------------------
    # Remove old vectors
    # --------------------------------------------------------

    deleted_count = (
        _delete_existing_document(
            collection=collection,
            filename=filename,
        )
    )

    if deleted_count:
        print(
            "[VectorStore] Removed "
            f"{deleted_count} old vector(s)."
        )

    # --------------------------------------------------------
    # Prepare Chroma records
    # --------------------------------------------------------

    ids: List[str] = []
    documents: List[str] = []
    metadatas: List[
        Dict[str, Any]
    ] = []

    for index, chunk in enumerate(
        clean_chunks
    ):
        chunk_id = _create_chunk_id(
            user_id=user_id,
            filename=filename,
            chunk_index=index,
            chunk=chunk,
        )

        page_metadata = (
            _build_page_metadata(
                chunk
            )
        )

        ids.append(
            chunk_id
        )

        documents.append(
            chunk
        )

        metadatas.append({
            "user_id": str(
                user_id
            ),
            "filename": filename,
            "chunk_index": index,
            "document_type": "pdf",
            "page_number": (
                page_metadata[
                    "page_number"
                ]
            ),
            "page_numbers": (
                page_metadata[
                    "page_numbers"
                ]
            ),
        })

        print(
            "[VectorStore] Chunk "
            f"{index + 1}: "
            f"pages="
            f"{page_metadata['page_numbers'] or 'unknown'} "
            f"| chars={len(chunk)}"
        )

    # --------------------------------------------------------
    # Store in batches
    # --------------------------------------------------------

    stored_count = 0

    try:
        for start in range(
            0,
            len(ids),
            BATCH_SIZE,
        ):
            end = min(
                start + BATCH_SIZE,
                len(ids),
            )

            collection.add(
                ids=ids[start:end],
                documents=documents[
                    start:end
                ],
                embeddings=clean_embeddings[
                    start:end
                ],
                metadatas=metadatas[
                    start:end
                ],
            )

            stored_count += (
                end - start
            )

            print(
                "[VectorStore] Stored batch: "
                f"{start + 1}-{end}"
            )

    except Exception as error:
        print(
            "[VectorStore] ChromaDB insertion failed:",
            repr(error),
        )

        # ----------------------------------------------------
        # Partial insertion cleanup
        # ----------------------------------------------------

        try:
            inserted_ids = ids[
                :stored_count
            ]

            if inserted_ids:
                collection.delete(
                    ids=inserted_ids
                )

                print(
                    "[VectorStore] Partial "
                    "insertion cleaned up."
                )

        except Exception as cleanup_error:
            print(
                "[VectorStore] Cleanup failed:",
                repr(cleanup_error),
            )

        raise RuntimeError(
            "Unable to store document vectors "
            "in ChromaDB."
        ) from error

    # --------------------------------------------------------
    # Final validation
    # --------------------------------------------------------

    if stored_count != len(
        clean_chunks
    ):
        raise RuntimeError(
            "Stored vector count does not "
            "match chunk count."
        )

    try:
        actual_count = (
            collection.count()
        )
    except Exception:
        actual_count = -1

    print(
        "[VectorStore] Document stored successfully."
    )

    print(
        "[VectorStore] Stored vectors "
        f"for this document: {stored_count}"
    )

    print(
        "[VectorStore] Total user collection "
        f"vectors: {actual_count}"
    )

    return stored_count


# ============================================================
# RETRIEVAL SCORING
# ============================================================

def _build_ranked_results(
    documents: List[str],
    metadatas: List[Dict[str, Any]],
    distances: List[float],
    ids: List[str],
    query_text: Optional[str],
) -> List[
    Tuple[
        float,
        int,
        Dict[str, Any],
    ]
]:
    """
    Build a combined retrieval ranking.

    Primary signal:
        Chroma semantic distance

    Secondary signal:
        lexical query-term coverage

    This is deliberately conservative:
    semantic similarity remains the main signal.
    """

    query_tokens = _tokenize(
        query_text or ""
    )

    ranked = []

    for index, document in enumerate(
        documents
    ):
        metadata = (
            metadatas[index]
            if index < len(metadatas)
            and metadatas[index]
            else {}
        )

        distance = (
            distances[index]
            if index < len(distances)
            else None
        )

        if distance is None:
            semantic_score = 0.0
        else:
            distance_value = _safe_float(
                distance,
                1.0,
            )

            # Cosine distance is generally smaller
            # for more similar vectors.
            #
            # Convert it to a bounded similarity-like
            # value for ranking only.
            semantic_score = max(
                0.0,
                1.0 - distance_value,
            )

        lexical_overlap = (
            _calculate_lexical_overlap(
                query_tokens,
                document,
            )
        )

        frequency_score = (
            _calculate_token_frequency_score(
                query_tokens,
                document,
            )
        )

        # Semantic score remains dominant.
        combined_score = (
            semantic_score * 0.80
            + lexical_overlap * 0.17
            + frequency_score * 0.03
        )

        ranked.append(
            (
                combined_score,
                index,
                {
                    "semantic_score": round(
                        semantic_score,
                        4,
                    ),
                    "lexical_overlap": round(
                        lexical_overlap,
                        4,
                    ),
                    "frequency_score": round(
                        frequency_score,
                        4,
                    ),
                    "distance": distance,
                    "id": (
                        ids[index]
                        if index < len(ids)
                        else None
                    ),
                    "metadata": metadata,
                },
            )
        )

    ranked.sort(
        key=lambda item: item[0],
        reverse=True,
    )

    return ranked


# ============================================================
# SEARCH CHUNKS
# ============================================================

def search_chunks(
    user_id: int,
    question_embedding: Sequence[float],
    n_results: int = 10,
    query_text: Optional[str] = None,
    min_distance: Optional[float] = DEFAULT_MIN_DISTANCE,
) -> Dict[str, Any]:
    """
    Semantic retrieval with conservative lexical reranking.

    Existing callers can continue using:

        search_chunks(
            user_id,
            question_embedding,
            n_results
        )

    Optional query_text improves ranking for terminology-heavy
    questions, especially OCR/scanned PDFs.

    No distance threshold is applied by default.
    """

    user_id = _validate_user_id(
        user_id
    )

    try:
        n_results = int(
            n_results
        )
    except (
        TypeError,
        ValueError,
    ) as error:
        raise ValueError(
            "n_results must be an integer."
        ) from error

    if n_results <= 0:
        raise ValueError(
            "n_results must be greater than 0."
        )

    query_embedding = (
        _embedding_to_list(
            question_embedding,
            0,
        )
    )

    query_dimension = len(
        query_embedding
    )

    collection = get_collection(
        user_id
    )

    try:
        total_vectors = (
            collection.count()
        )
    except Exception as error:
        print(
            "[VectorStore] Failed to read collection:",
            repr(error),
        )

        raise RuntimeError(
            "Unable to read ChromaDB collection."
        ) from error

    if total_vectors == 0:
        print(
            "[VectorStore] Collection is empty."
        )

        return {
            "ids": [[]],
            "documents": [[]],
            "metadatas": [[]],
            "distances": [[]],
        }

    # --------------------------------------------------------
    # Retrieve extra candidates.
    #
    # We intentionally retrieve more than the final requested
    # number when possible so lexical reranking has enough
    # candidates to work with.
    # --------------------------------------------------------

    candidate_count = min(
        max(
            n_results * 2,
            DEFAULT_SEARCH_RESULTS,
        ),
        total_vectors,
    )

    print()
    print(
        "[VectorStore] Semantic search:"
    )
    print(
        f"  User ID          : {user_id}"
    )
    print(
        f"  Query dimension  : {query_dimension}"
    )
    print(
        f"  Requested results: {n_results}"
    )
    print(
        f"  Candidates       : {candidate_count}"
    )
    print(
        f"  Collection size  : {total_vectors}"
    )

    if query_text:
        print(
            "[VectorStore] Query text       : "
            f"{str(query_text).strip()[:180]}"
        )

    # --------------------------------------------------------
    # Chroma query
    # --------------------------------------------------------

    try:
        results = collection.query(
            query_embeddings=[
                query_embedding
            ],
            n_results=candidate_count,
            include=[
                "documents",
                "metadatas",
                "distances",
            ],
        )

    except Exception as error:
        print(
            "[VectorStore] ChromaDB search failed:",
            repr(error),
        )

        raise RuntimeError(
            "Unable to search ChromaDB."
        ) from error

    result_documents = (
        results.get(
            "documents",
            [[]],
        )
        or [[]]
    )

    result_metadatas = (
        results.get(
            "metadatas",
            [[]],
        )
        or [[]]
    )

    result_distances = (
        results.get(
            "distances",
            [[]],
        )
        or [[]]
    )

    result_ids = (
        results.get(
            "ids",
            [[]],
        )
        or [[]]
    )

    documents = (
        result_documents[0]
        if result_documents
        else []
    )

    metadatas = (
        result_metadatas[0]
        if result_metadatas
        else []
    )

    distances = (
        result_distances[0]
        if result_distances
        else []
    )

    ids = (
        result_ids[0]
        if result_ids
        else []
    )

    print(
        "[VectorStore] Search returned "
        f"{len(documents)} candidate(s)."
    )

    if not documents:
        return {
            "ids": [[]],
            "documents": [[]],
            "metadatas": [[]],
            "distances": [[]],
        }

    # --------------------------------------------------------
    # Optional distance threshold
    # --------------------------------------------------------

    eligible_indices: List[int] = []

    for index, document in enumerate(
        documents
    ):
        distance = (
            distances[index]
            if index < len(distances)
            else None
        )

        if (
            min_distance is not None
            and distance is not None
            and _safe_float(
                distance,
                999.0,
            ) > float(min_distance)
        ):
            print(
                "[VectorStore] Candidate "
                f"{index + 1} rejected by "
                "distance threshold."
            )
            continue

        eligible_indices.append(
            index
        )

    # --------------------------------------------------------
    # Never return an accidental empty context only because
    # an optional threshold was too strict.
    # --------------------------------------------------------

    if (
        not eligible_indices
        and documents
    ):
        print(
            "[VectorStore] Distance threshold "
            "removed all candidates; "
            "restoring semantic candidates."
        )

        eligible_indices = list(
            range(len(documents))
        )

    filtered_documents = [
        documents[index]
        for index in eligible_indices
    ]

    filtered_metadatas = [
        (
            metadatas[index]
            if index < len(metadatas)
            else {}
        )
        for index in eligible_indices
    ]

    filtered_distances = [
        (
            distances[index]
            if index < len(distances)
            else None
        )
        for index in eligible_indices
    ]

    filtered_ids = [
        (
            ids[index]
            if index < len(ids)
            else ""
        )
        for index in eligible_indices
    ]

    # --------------------------------------------------------
    # Combined semantic + lexical ranking
    # --------------------------------------------------------

    ranked = _build_ranked_results(
        documents=filtered_documents,
        metadatas=filtered_metadatas,
        distances=filtered_distances,
        ids=filtered_ids,
        query_text=query_text,
    )

    # --------------------------------------------------------
    # Final results
    # --------------------------------------------------------

    final_limit = min(
        n_results,
        len(ranked),
    )

    selected = ranked[
        :final_limit
    ]

    output_documents: List[str] = []
    output_metadatas: List[
        Dict[str, Any]
    ] = []
    output_distances: List[
        Optional[float]
    ] = []
    output_ids: List[str] = []

    print(
        "[VectorStore] Final ranked results:"
    )

    for rank, (
        combined_score,
        _index,
        diagnostic,
    ) in enumerate(
        selected,
        start=1,
    ):
        metadata = diagnostic[
            "metadata"
        ]

        selected_id = (
            diagnostic.get(
                "id"
            )
        )

        # The source document corresponding to the selected
        # ranking item.
        original_index = ranked[
            rank - 1
        ][1]

        selected_document = (
            filtered_documents[
                original_index
            ]
        )

        selected_distance = (
            filtered_distances[
                original_index
            ]
            if original_index
            < len(filtered_distances)
            else None
        )

        output_documents.append(
            selected_document
        )

        output_metadatas.append(
            metadata
        )

        output_distances.append(
            selected_distance
        )

        if selected_id is not None:
            output_ids.append(
                selected_id
            )

        print(
            f"  {rank}. "
            f"{metadata.get('filename', 'Unknown')} "
            f"| page(s)="
            f"{metadata.get('page_numbers', 'unknown')} "
            f"| distance="
            f"{diagnostic['distance']} "
            f"| semantic="
            f"{diagnostic['semantic_score']} "
            f"| lexical="
            f"{diagnostic['lexical_overlap']} "
            f"| combined="
            f"{combined_score:.4f}"
        )

    return {
        "ids": [
            output_ids
        ],
        "documents": [
            output_documents
        ],
        "metadatas": [
            output_metadatas
        ],
        "distances": [
            output_distances
        ],
    }



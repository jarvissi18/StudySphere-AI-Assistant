# DELETE DOCUMENT EMBEDDINGS
# ============================================================

def delete_pdf_embeddings(
    user_id: int,
    filename: str,
) -> int:
    """
    Delete all indexed vectors for one PDF.
    """

    user_id = _validate_user_id(
        user_id
    )

    filename = _clean_filename(
        filename
    )

    collection = get_collection(
        user_id
    )

    try:
        existing = collection.get(
            where={
                "filename": filename
            },
            include=["metadatas"],
        )

        ids = (
            existing.get(
                "ids",
                [],
            )
            if existing
            else []
        )

        if not ids:
            print(
                "[VectorStore] No vectors "
                f"found for: {filename}"
            )
            return 0

        collection.delete(
            ids=ids
        )

        print(
            "[VectorStore] Deleted "
            f"{len(ids)} vector(s) "
            f"for '{filename}'."
        )

        return len(ids)

    except Exception as error:
        print(
            "[VectorStore] Failed to delete vectors:",
            repr(error),
        )

        raise RuntimeError(
            "Unable to delete document vectors."
        ) from error


